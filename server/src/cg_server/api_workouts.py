"""REST for workouts (Android app, `/api/v1`, app token).

- `POST /workouts` creates a draft, idempotent by `client_id` (UUID from the app):
  201 when created, 200 with the existing workout when the `client_id` is known.
- `POST /workouts/{id}/schedule` queues it for a date in the outbox (one entry per
  workout and day) and tries to send it at once, in the background.
- `GET /scheduled?from&to` -> `{"items": [...]}`, `DELETE /scheduled/{id}`
  (only this user's entries).
"""

from datetime import date, datetime, timedelta
from typing import Annotated
from zoneinfo import ZoneInfo

from fastapi import (
    APIRouter,
    BackgroundTasks,
    Depends,
    HTTPException,
    Query,
    Request,
    Response,
    status,
)
from pydantic import UUID4, BaseModel, Field
from sqlalchemy.orm import Session

from cg_server import workouts
from cg_server.api import CurrentUser, db_session
from cg_server.models import ScheduleStatus, WorkoutOrigin
from cg_server.outbox import OutboxRunner
from cg_server.workout_definition import DefinitionError, WorkoutDefinition
from cg_server.workout_views import (
    ScheduledList,
    ScheduledOut,
    WorkoutOut,
    scheduled_out,
    workout_out,
)

MAX_LIST_DAYS = 366

router = APIRouter(prefix="/api/v1")
Db = Annotated[Session, Depends(db_session)]


class NewWorkout(BaseModel):
    client_id: UUID4 = Field(description="Generated by the app; repeating it is a no-op.")
    definition: WorkoutDefinition


class ScheduleRequest(BaseModel):
    date: date


def _today(request: Request) -> date:
    return datetime.now(ZoneInfo(request.app.state.settings.timezone)).date()


def _send_soon(request: Request, tasks: BackgroundTasks, user_id: int) -> None:
    outbox: OutboxRunner | None = getattr(request.app.state, "outbox", None)
    if outbox is not None:
        tasks.add_task(outbox.run_user, user_id)


@router.post("/workouts", status_code=status.HTTP_201_CREATED)
def create_workout(
    body: NewWorkout, user: CurrentUser, session: Db, response: Response
) -> WorkoutOut:
    try:
        workout, created = workouts.create_workout(
            session,
            user,
            body.definition,
            client_id=str(body.client_id),
            origin=WorkoutOrigin.APP,
        )
    except (DefinitionError, workouts.WorkoutError) as e:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, detail=str(e)) from None
    if not created:
        response.status_code = status.HTTP_200_OK
    return workout_out(workout)


@router.post("/workouts/{workout_id}/schedule", status_code=status.HTTP_201_CREATED)
def schedule_workout(
    workout_id: int,
    body: ScheduleRequest,
    user: CurrentUser,
    session: Db,
    request: Request,
    response: Response,
    tasks: BackgroundTasks,
) -> ScheduledOut:
    try:
        item, created = workouts.schedule_workout(
            session, user, workout_id, body.date, today=_today(request)
        )
    except workouts.NotFound:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Nie znaleziono") from None
    except workouts.WorkoutError as e:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_CONTENT, detail=str(e)) from None
    if not created:
        response.status_code = status.HTTP_200_OK
    if item.status == ScheduleStatus.PENDING:
        _send_soon(request, tasks, user.id)
    return scheduled_out(item)


@router.get("/scheduled")
def list_scheduled(
    user: CurrentUser,
    session: Db,
    request: Request,
    from_: Annotated[date | None, Query(alias="from")] = None,
    to: date | None = None,
) -> ScheduledList:
    start = from_ or _today(request)
    end = to or start + timedelta(days=30)
    if end < start or (end - start).days > MAX_LIST_DAYS:
        raise HTTPException(
            status.HTTP_422_UNPROCESSABLE_CONTENT,
            detail=f"'to' must be after 'from', at most {MAX_LIST_DAYS} days",
        )
    items = workouts.list_scheduled(session, user, start, end)
    return ScheduledList(items=[scheduled_out(i) for i in items])


@router.delete("/scheduled/{scheduled_id}")
def delete_scheduled(
    scheduled_id: int,
    user: CurrentUser,
    session: Db,
    request: Request,
    tasks: BackgroundTasks,
) -> ScheduledOut:
    try:
        item = workouts.request_delete(session, user, scheduled_id)
    except workouts.NotFound:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Nie znaleziono") from None
    if item.status == ScheduleStatus.DELETING:
        _send_soon(request, tasks, user.id)
    return scheduled_out(item)
